fn find(table: &'static [(&'static str, &'static str)], name: &str) -> Option<&'static str> {
	let name = name.strip_prefix("minecraft:").unwrap_or(name);
	table.iter().find(|(n, _)| *n == name).map(|(_, s)| *s)
}

pub(super) fn substitute(name: &str) -> Option<&'static str> {
	find(BLOCKS, name)
}

pub(super) fn item(name: &str) -> Option<&'static str> {
	find(ITEMS, name)
}

pub(super) fn sound(name: &str) -> Option<&'static str> {
	find(SOUNDS, name)
}
