pub fn block_changes(to: V) -> bool {
	matches!(
		to,
		V::R1_1 | V::R1_2_5 | V::R1_3 | V::R1_4_7 | V::R1_5 | V::R1_6_4
	)
}

pub fn mob_exists(kind: u8, to: V) -> bool {
	let since = match kind {
		50..=63 | 90..=97 | 120 => V::R1_0,
		98 | 99 => V::R1_2_3,
		64..=66 => V::R1_4_2,
		100 => V::R1_6_1,
		_ => return false,
	};
	since <= to
}

pub fn object_exists(kind: i8, to: V) -> bool {
	let since = match kind {
		75 => V::R1_2_3,
		66 | 71 => V::R1_4_2,
		76 => V::R1_4_7,
		77 => V::R1_6_1,
		_ => V::R1_0,
	};
	since <= to
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn items_fall_back_through_every_older_release() {
		assert_eq!(item(383, 100, V::R1_6_4), (383, 100));
		assert_eq!(item(383, 100, V::R1_5), (383, 90));
		assert_eq!(item(383, 100, V::R1_0), (344, 0));
		assert_eq!(item(156, 2, V::R1_4_7), (128, 0));
		assert_eq!(item(156, 2, V::R1_2_5), (67, 0));
		assert_eq!(item(1, 0, V::R1_0), (1, 0));
	}

	#[test]
	fn blocks_keep_meta_where_it_still_means_something() {
		assert_eq!(block(126, 9, V::R1_2_5), (44, 10));
		assert_eq!(block(162, 5, V::R1_6_4), (17, 4));
		assert_eq!(block(171, 3, V::R1_5), (0, 0));
		assert_eq!(block(171, 3, V::R1_6_4), (171, 3));
	}
}
