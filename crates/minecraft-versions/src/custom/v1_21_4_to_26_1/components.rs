pub fn names(version: Version) -> &'static [&'static str] {
	match version {
		Version::V1_21_4 => C1_21_4,
		Version::V1_21_5 | Version::V1_21_6 | Version::V1_21_8 | Version::V1_21_9 => C1_21_5,
		Version::V1_21_11 => C1_21_11,
		_ => C26_1,
	}
}

pub fn id(version: Version, name: &str) -> Option<i32> {
	names(version)
		.iter()
		.position(|n| *n == name)
		.map(|i| i as i32)
}

pub fn name(version: Version, id: i32) -> Option<&'static str> {
	names(version).get(usize::try_from(id).ok()?).copied()
}

pub fn remap(from: Version, to: Version, id: i32) -> Option<i32> {
	self::id(to, name(from, id)?)
}

pub fn retag<A, B>(
	map: impl Fn(i32) -> Option<i32>,
	v: &A,
	ser: impl Fn(&A, &mut crate::pds::Output) -> crate::pds::Result<()>,
	de: impl Fn(&mut crate::pds::Input) -> crate::pds::Result<B>,
) -> crate::pds::convert::Result<Option<B>> {
	use super::util::{decode, encode, read_varint, write_varint};
	let bytes = encode(v, ser)?;
	let mut at = 0;
	let Some(tag) = map(read_varint(&bytes, &mut at)?) else {
		return Ok(None);
	};
	let mut out = Vec::with_capacity(bytes.len());
	write_varint(&mut out, tag);
	out.extend_from_slice(&bytes[at..]);
	decode(&out, de).map(Some)
}
